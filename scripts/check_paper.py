#!/usr/bin/env python3
"""Build declared Lean targets and audit their transitive axiom dependencies.

Python 3.10+, standard library only. This checks machine evidence, not whether
the Lean statements express a paper. It never publishes a verification label.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from typing import Any


OWNER = "paper-formalization/check_paper.py:v1"
AUDIT_HEADER = "-- Generated by paper-formalization/check_paper.py; do not edit."
LEAN_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*\Z")
SHA256 = re.compile(r"[0-9a-fA-F]{64}\Z")
STANDARD_TOOLCHAIN = re.compile(r"leanprover/lean4:v([0-9]+\.[0-9]+\.[0-9]+(?:-rc[0-9]+)?)\Z")
ALLOWED_AXIOMS = ["propext", "Classical.choice", "Quot.sound"]
EXCLUDED_DIRECTORIES = {".git", ".lake", ".paper-verification", ".tools", ".references"}


class CheckError(Exception):
    """A failed validation or Lean command."""


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def digest(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            hasher.update(block)
    return hasher.hexdigest()


def fingerprint(value: Any) -> str:
    data = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def inside(repo: Path, path: Path, description: str) -> Path:
    path = path.resolve()
    if not path.is_relative_to(repo):
        raise CheckError(f"{description} must stay inside repository: {path}")
    return path


def repo_path(repo: Path, value: str, description: str) -> Path:
    supplied = Path(value)
    return inside(repo, supplied if supplied.is_absolute() else repo / supplied, description)


def require_text(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise CheckError(f"{field} must be a nonempty string")
    return value


def load_manifest(path: Path) -> dict[str, Any]:
    try:
        manifest = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as error:
        raise CheckError(f"Cannot read manifest: {error}") from error
    if not isinstance(manifest, dict) or type(manifest.get("schema_version")) is not int:
        raise CheckError("Manifest requires integer schema_version=1")
    if manifest["schema_version"] != 1:
        raise CheckError("Only schema_version=1 is supported")
    paper = manifest.get("paper")
    if not isinstance(paper, dict):
        raise CheckError("paper must be an object")
    for key in ("title", "version", "sha256"):
        require_text(paper.get(key), f"paper.{key}")
    if not SHA256.fullmatch(paper["sha256"]):
        raise CheckError("paper.sha256 must contain 64 hexadecimal characters")
    if paper["sha256"] == "0" * 64:
        raise CheckError("paper.sha256 is the unconfigured all-zero template value")
    scope = manifest.get("scope")
    if not isinstance(scope, dict) or scope.get("kind") not in ("selected-results", "paper-results"):
        raise CheckError("scope.kind must be selected-results or paper-results")
    require_text(scope.get("description"), "scope.description")
    targets = manifest.get("targets")
    if not isinstance(targets, list) or not targets:
        raise CheckError("targets must be a nonempty array")
    claim_ids: set[str] = set()
    declarations: set[str] = set()
    for index, target in enumerate(targets):
        if not isinstance(target, dict):
            raise CheckError(f"targets[{index}] must be an object")
        for key in ("claim_id", "module", "declaration"):
            require_text(target.get(key), f"targets[{index}].{key}")
        for key in ("module", "declaration"):
            if not LEAN_NAME.fullmatch(target[key]):
                raise CheckError(f"targets[{index}].{key}: only ASCII dotted Lean identifiers supported")
        if target["claim_id"] in claim_ids or target["declaration"] in declarations:
            raise CheckError("Duplicate claim_id or declaration; use separate subclaim IDs")
        claim_ids.add(target["claim_id"])
        declarations.add(target["declaration"])
    return manifest


def git_metadata(repo: Path, output: Path) -> dict[str, Any]:
    try:
        head = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "HEAD"],
            capture_output=True, text=True, encoding="utf-8", errors="replace", check=False,
        )
        if head.returncode != 0:
            return {"available": False, "reason": "No Git HEAD available"}
        excluded = f":(exclude){output.relative_to(repo).as_posix()}"
        status = subprocess.run(
            ["git", "-C", str(repo), "status", "--porcelain=v1", "--untracked-files=all", "--", ".", excluded],
            capture_output=True, text=True, encoding="utf-8", errors="replace", check=False,
        )
        return {
            "available": True,
            "head": head.stdout.strip(),
            "dirty": bool(status.stdout) if status.returncode == 0 else None,
            "status": status.stdout.splitlines() if status.returncode == 0 else [],
            "output_directory_excluded": output.relative_to(repo).as_posix(),
        }
    except OSError as error:
        return {"available": False, "reason": str(error)}


def tracked_by_git(repo: Path, path: Path) -> bool:
    try:
        result = subprocess.run(
            ["git", "-C", str(repo), "ls-files", "--error-unmatch", "--", path.relative_to(repo).as_posix()],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False,
        )
        return result.returncode == 0
    except OSError:
        return False


def owned_result_writable(repo: Path, output: Path) -> bool:
    """Allow a new failure receipt even if a later preflight rejects the audit."""
    try:
        if output == repo or any(part in (".git", ".lake") for part in output.relative_to(repo).parts):
            return False
        marker = output / ".check-paper-owner.json"
        result = output / "result.json"
        return (
            output.is_dir()
            and not marker.is_symlink()
            and json.loads(marker.read_text(encoding="utf-8")) == {"owner": OWNER}
            and not result.is_symlink()
            and not tracked_by_git(repo, result)
        )
    except (OSError, ValueError):
        return False


def prepare_output(repo: Path, output: Path) -> None:
    if output == repo or any(part in (".git", ".lake") for part in output.relative_to(repo).parts):
        raise CheckError("Output must be a dedicated subdirectory outside .git and .lake")
    marker = output / ".check-paper-owner.json"
    if output.exists() and not output.is_dir():
        raise CheckError("Output path is not a directory")
    if output.exists() and any(output.iterdir()):
        try:
            owner = json.loads(marker.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise CheckError("Refusing to overwrite a nonempty output directory without this script's owner marker") from error
        if owner != {"owner": OWNER}:
            raise CheckError("Output directory has a different owner marker")
    for filename in ("CheckTargets.lean", "build.log", "audit.log", "runtime.log", "result.json", marker.name):
        file = output / filename
        if file.exists() and (file.is_symlink() or tracked_by_git(repo, file)):
            raise CheckError(f"Refusing to overwrite symlink or Git-tracked output: {file}")
    audit = output / "CheckTargets.lean"
    if audit.exists() and not audit.read_text(encoding="utf-8").startswith(AUDIT_HEADER + "\n"):
        raise CheckError("Refusing to overwrite a repository-supplied audit file")
    output.mkdir(parents=True, exist_ok=True)
    marker.write_text(json.dumps({"owner": OWNER}) + "\n", encoding="utf-8")
    if audit.exists():
        audit.unlink()
    for filename in ("build.log", "audit.log", "runtime.log"):
        (output / filename).write_text("Not run.\n", encoding="utf-8")
    # Invalidate prior success before any new preflight or compiler invocation.
    (output / "result.json").write_text(
        json.dumps({"status": "failed", "error": "Run has not completed", "started_at": utc_now()}, indent=2) + "\n",
        encoding="utf-8",
    )


def source_snapshot(repo: Path, output: Path) -> dict[str, str]:
    sources: dict[str, str] = {}
    for current, dirs, files in os.walk(repo, followlinks=False):
        folder = Path(current)
        kept = []
        for dirname in dirs:
            child = folder / dirname
            if dirname in EXCLUDED_DIRECTORIES or child.resolve() == output:
                continue
            if child.is_symlink():
                raise CheckError(f"Cannot snapshot a symlinked source directory: {child}")
            kept.append(dirname)
        dirs[:] = kept
        for filename in files:
            if not filename.endswith(".lean"):
                continue
            source = folder / filename
            if source.is_symlink():
                raise CheckError(f"Cannot snapshot a symlinked Lean source: {source}")
            sources[source.relative_to(repo).as_posix()] = digest(source)
    return dict(sorted(sources.items()))


def input_snapshot(repo: Path, output: Path, manifest_path: Path) -> dict[str, Any]:
    required = (repo / "lean-toolchain", repo / "lake-manifest.json", manifest_path)
    for path in required:
        inside(repo, path, "Input")
        if not path.is_file():
            raise CheckError(f"Required input missing: {path}")
    sources = source_snapshot(repo, output)
    result: dict[str, Any] = {
        "manifest_path": manifest_path.relative_to(repo).as_posix(),
        "manifest_sha256": digest(manifest_path),
        "lean_toolchain": (repo / "lean-toolchain").read_text(encoding="utf-8-sig").strip(),
        "lean_toolchain_sha256": digest(repo / "lean-toolchain"),
        "lake_manifest_sha256": digest(repo / "lake-manifest.json"),
        "lakefiles": {name: digest(repo / name) for name in ("lakefile.lean", "lakefile.toml") if (repo / name).is_file()},
        "lean_sources": sources,
        "lean_sources_fingerprint": fingerprint(sources),
        "source_hash_excluded_directories": sorted(EXCLUDED_DIRECTORIES),
        "checker_sha256": digest(Path(__file__).resolve()),
    }
    if not result["lean_toolchain"]:
        raise CheckError("lean-toolchain is empty")
    if not result["lakefiles"]:
        raise CheckError("No lakefile.lean or lakefile.toml found")
    result["input_fingerprint"] = fingerprint(result)
    return result


def audit_source(targets: list[dict[str, str]]) -> str:
    modules = sorted({target["module"] for target in targets})
    imports = "\n".join(f"import {module}" for module in modules)
    target_pairs = ",\n    ".join(f"(`{target['declaration']}, `{target['module']})" for target in targets)
    checks = "\n".join(f"#check @{target['declaration']}\n#print axioms {target['declaration']}" for target in targets)
    return f"""{AUDIT_HEADER}
-- A plain file intentionally imports private proof data; do not add `module`.
{imports}
import Lean.Elab.Command
import Lean.Util.CollectAxioms

set_option pp.explicit true
set_option pp.fullNames true
set_option pp.universes true
set_option pp.proofs false

open Lean Elab Command

run_cmd do
  let env ← getEnv
  let allowed : List Name := [``propext, ``Classical.choice, ``Quot.sound]
  let targets : List (Name × Name) := [
    {target_pairs}]
  for (decl, expectedModule) in targets do
    let some info := env.find? decl
      | throwError "Target declaration is missing: {{decl}}"
    unless info matches .thmInfo _ do
      throwError "Target must be a proved theorem, not an axiom or definition: {{decl}}"
    let some moduleIdx := env.getModuleIdxFor? decl
      | throwError "No defining module for target: {{decl}}"
    let some actualModule := env.header.moduleNames[moduleIdx.toNat]?
      | throwError "Missing defining module data for target: {{decl}}"
    unless actualModule == expectedModule do
      throwError "Target {{decl}} is defined in {{actualModule}}, expected {{expectedModule}}"
    let axioms ← collectAxioms decl
    let bad := axioms.filter fun ax => !allowed.contains ax
    unless bad.isEmpty do
      throwError "Target {{decl}} depends on disallowed axioms: {{bad}}"
    logInfo m!"Target {{decl}} passed the axiom check; axioms: {{axioms}}"

{checks}
"""


def command(argv: list[str], repo: Path, log: Path, timeout: int) -> int:
    print("Running " + json.dumps(argv, ensure_ascii=False), flush=True)
    with log.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("Command: " + json.dumps(argv, ensure_ascii=False) + "\n")
        stream.flush()
        try:
            process = subprocess.run(argv, cwd=repo, stdout=stream, stderr=subprocess.STDOUT, shell=False, timeout=timeout, check=False)
        except subprocess.TimeoutExpired as error:
            stream.write(f"\nERROR: command exceeded {timeout} seconds.\n")
            raise CheckError(f"Command timed out; see {log}") from error
        except OSError as error:
            stream.write(f"\nERROR: {error}\n")
            raise CheckError(f"Cannot execute command; see {log}: {error}") from error
        stream.write(f"\nExit code: {process.returncode}\n")
    return process.returncode


def runtime_versions(args: argparse.Namespace, repo: Path, output: Path, expected: str, result: dict[str, Any]) -> None:
    runtime: dict[str, Any] = {}
    result["runtime"] = runtime
    with (output / "runtime.log").open("w", encoding="utf-8", newline="\n") as stream:
        for name, argv in (
            ("lake", [args.lake, "--version"]),
            ("lean", [args.lake, "env", "lean", "--version"]),
        ):
            stream.write("Command: " + json.dumps(argv, ensure_ascii=False) + "\n")
            stream.flush()
            try:
                process = subprocess.run(argv, cwd=repo, capture_output=True, text=True, encoding="utf-8", errors="replace", shell=False, timeout=args.timeout, check=False)
            except (OSError, subprocess.TimeoutExpired) as error:
                stream.write(f"ERROR: {error}\n")
                raise CheckError(f"Cannot inspect actual {name} version; see {output / 'runtime.log'}") from error
            runtime[name] = {"command": argv, "returncode": process.returncode, "stdout": process.stdout, "stderr": process.stderr}
            stream.write(process.stdout + process.stderr + f"\nExit code: {process.returncode}\n")
            if process.returncode != 0:
                raise CheckError(f"Actual {name} version command failed; see {output / 'runtime.log'}")
    pin = STANDARD_TOOLCHAIN.fullmatch(expected)
    observed = re.search(r"Lean \(version ([^,\s)]+)", runtime["lean"]["stdout"])
    runtime["lean_version"] = observed.group(1) if observed else None
    runtime["expected_toolchain"] = expected
    if pin:
        runtime["toolchain_runtime_match"] = observed is not None and observed.group(1) == pin.group(1)
        runtime["toolchain_match_status"] = "matched" if runtime["toolchain_runtime_match"] else "mismatch"
        if not runtime["toolchain_runtime_match"]:
            raise CheckError(f"Actual Lean version {runtime['lean_version']!r} does not match lean-toolchain {expected!r}")
    else:
        runtime["toolchain_runtime_match"] = None
        runtime["toolchain_match_status"] = "manual-check-required"
        runtime["note"] = "Nightly/custom toolchain identity requires manual verification; no version match is asserted"


def run(args: argparse.Namespace) -> int:
    repo = Path(args.repo).resolve()
    result: dict[str, Any] = {
        "schema_version": 1,
        "status": "failed",
        "started_at": utc_now(),
        "paper_hash_verified": False,
        "semantic_correspondence_verified": False,
        "allowed_axioms": ALLOWED_AXIOMS,
        "scope_of_machine_check": "Listed theorem declarations and their transitive axiom dependencies only",
    }
    output: Path | None = None
    writable_output = False
    try:
        if not repo.is_dir():
            raise CheckError(f"Repository directory does not exist: {repo}")
        output = repo_path(repo, args.output, "Output")
        # Recognize our previous receipt before validation; a rejected rerun must
        # not leave its previous success looking like the latest outcome.
        writable_output = owned_result_writable(repo, output)
        result["git"] = git_metadata(repo, output)
        prepare_output(repo, output)
        writable_output = True
        manifest_path = repo_path(repo, args.manifest, "Manifest")
        if manifest_path == output or manifest_path.is_relative_to(output):
            raise CheckError("Manifest cannot be inside the generated output directory")
        for name in ("lean-toolchain", "lake-manifest.json", "lakefile.lean", "lakefile.toml"):
            if (repo / name).is_relative_to(output):
                raise CheckError("Output directory cannot contain project configuration")
        manifest = load_manifest(manifest_path)
        result["paper"] = manifest["paper"]
        result["scope"] = manifest["scope"]
        result["targets"] = manifest["targets"]
        before = input_snapshot(repo, output, manifest_path)
        result["inputs"] = before
        runtime_versions(args, repo, output, before["lean_toolchain"], result)
        modules = sorted({target["module"] for target in manifest["targets"]})
        for module in modules:
            module_path = repo.joinpath(*module.split(".")).with_suffix(".lean")
            if not module_path.is_file() or not module_path.resolve().is_relative_to(repo):
                raise CheckError(f"Target module must have a local source file: {module}")
        build_command = [args.lake, "build", *modules]
        result["build_command"] = build_command
        result["build_returncode"] = command(build_command, repo, output / "build.log", args.timeout)
        if result["build_returncode"] != 0:
            raise CheckError(f"Lean build failed; see {output / 'build.log'}")
        audit = output / "CheckTargets.lean"
        audit.write_text(audit_source(manifest["targets"]), encoding="utf-8", newline="\n")
        result["audit_sha256"] = digest(audit)
        audit_command = [args.lake, "env", "lean", str(audit)]
        result["audit_command"] = audit_command
        result["audit_returncode"] = command(audit_command, repo, output / "audit.log", args.timeout)
        if result["audit_returncode"] != 0:
            raise CheckError(f"Lean theorem or axiom audit failed; see {output / 'audit.log'}")
        after = input_snapshot(repo, output, manifest_path)
        if before != after:
            result["inputs_after"] = after
            raise CheckError("Inputs changed during verification; rerun against an unchanged source tree")
        result["status"] = "machine-check-passed"
    except (CheckError, OSError, ValueError) as error:
        result["error"] = str(error)
        print(f"ERROR: {error}", file=sys.stderr)
    finally:
        result["finished_at"] = utc_now()
        if writable_output and output is not None:
            for name in ("build.log", "audit.log", "runtime.log"):
                log = output / name
                if log.is_file() and not log.is_symlink():
                    result.setdefault("log_sha256", {})[name] = digest(log)
            (output / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            print(f"{result['status']}: {output / 'result.json'}", flush=True)
    return 0 if result["status"] == "machine-check-passed" else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=".", help="Lean repository directory (default: current directory)")
    parser.add_argument("--manifest", default="docs/formalization/scope.json", help="Manifest path inside repository")
    parser.add_argument("--lake", default="lake", help="Lake executable or path; executed without a shell")
    parser.add_argument("--output", default=".paper-verification", help="Dedicated generated directory inside repository")
    parser.add_argument("--timeout", type=int, default=1800, help="Maximum seconds per Lean command (default: 1800)")
    args = parser.parse_args()
    if args.timeout <= 0:
        parser.error("--timeout must be positive")
    return run(args)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
